#!/usr/bin/env python3
"""Lucide icons as C# data for Components/Ui/Icon.razor.

Reads node_modules/lucide-static/icons/<name>.svg (npm install first) and writes Components/Ui/LucideIcons.g.cs with
the inner markup of each icon listed in ICONS. Add a name here and run: python3 tools/generate-icons.py
"""
import pathlib
import re

ICONS = sorted("""
activity arrow-left arrow-right badge-check bell bike building-2 calendar car chart-column check chevron-down
chevron-left chevron-right chevrons-up-down circle circle-alert circle-check circle-dot clipboard-check clock
credit-card database ellipsis external-link eye file-check file-text gauge handshake id-card inbox layout-dashboard
list loader-circle lock-keyhole log-out mail map map-pin menu moon navigation package package-check package-search
pill flower-2 shopping-basket gift eye-off store tag weight ruler wine
history pencil phone plus receipt refresh-cw route scale search shield-check sliders-horizontal smartphone store sun timer
minus shopping-cart ban trash-2 triangle-alert truck user-round users utensils wallet x zap
""".split())

root = pathlib.Path(__file__).resolve().parent.parent
source = root / "node_modules" / "lucide-static" / "icons"
version = re.search(r'"version":\s*"([^"]+)"', (source.parent / "package.json").read_text()).group(1)

lines = [
    "// <auto-generated> by tools/generate-icons.py from lucide-static " + version + " (ISC license). Do not edit.",
    "namespace Shipment.Api.Components.Ui;",
    "",
    "internal static class LucideIcons",
    "{",
    "    public static readonly IReadOnlyDictionary<string, string> Markup = new Dictionary<string, string>",
    "    {",
]
for name in ICONS:
    svg = (source / f"{name}.svg").read_text()
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    inner = " ".join(part.strip() for part in inner.strip().splitlines())
    lines.append(f'        ["{name}"] = "{inner.replace(chr(34), chr(92) + chr(34))}",')
lines += ["    };", "}", ""]
(root / "Components" / "Ui" / "LucideIcons.g.cs").write_text("\n".join(lines))
print(f"{len(ICONS)} icons from lucide-static {version}")
